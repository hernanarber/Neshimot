export const STRINGS = { en: EN, he: HE };

let LANG = 'en';
export const lang = () => LANG;
export const isHe = () => LANG === 'he';
export const locale = () => (LANG === 'he' ? 'he-IL' : 'en-GB');

/** Set the language for interface strings and exercise content. */
export function setLang(l) {
  LANG = l === 'he' ? 'he' : 'en';
  setDataLang(LANG);
}

export function t(key, vars) {
  const v = STRINGS[LANG][key] ?? EN[key];
  if (v == null) throw new Error(`Missing string: ${key}`);
  if (typeof v === 'function') return v(vars || {});
  return vars ? v.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m)) : v;
}
